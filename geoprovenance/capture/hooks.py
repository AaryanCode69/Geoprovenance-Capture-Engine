def install_all(engine: ProvenanceCaptureEngine, hook_dir) -> list[tuple[str, Callable]]:
    """Install the hook channels. Returns (description, undo) pairs for §5.4.

    All of them are installed because until §5.11's coverage table is filled in
    we do not know which invocation paths the hook covers, and a missed
    execution is an RQ1 result we would rather measure than suffer.

    The pre-execution hook is not a channel of its own — it records nothing.
    It only leaves a start time for the post hook to pick up (A5).
    """
    return [
        ("restore the pre-execution hook setting", install_pre_execution_hook(hook_dir)),
        ("restore the post-execution hook setting", install_post_execution_hook(hook_dir)),
        ("un-patch processing.run", install_run_wrapper(engine)),
    ]
