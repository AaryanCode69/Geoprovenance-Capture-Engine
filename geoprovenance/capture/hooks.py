# channel 1: the post-execution hook
# ---------------------------------------------------------------------------

def handle_pre_execution(scope: dict) -> None:
    """Called by the generated pre-execution script. Stamps the start time.

    A5. Without this the post-execution hook is the only thing that fires, and
    it fires *after* the run — so every job looked instantaneous and
    `post_hook` durations were not reportable in RQ2 at all (§8.4).

    Never raises (§5.1): a missing start time costs a duration, and the engine
    falls back to "now", which is the pre-A5 behaviour rather than a failure.
    """
    global _pending_start, _pre_namespace_logged
    try:
        if not _pre_namespace_logged:
            names = sorted(k for k in scope if not k.startswith("_"))
            log(f"pre-execution hook namespace: {names}. "
                f"Record this in docs/capture_coverage.md §4 (§5.11).", INFO)
            _pre_namespace_logged = True
        _pending_start = utc_now_iso()
    except Exception as exc:  # noqa: BLE001 — §5.1 [HARD]
        log_exception("pre-execution hook", exc)


def take_pending_start() -> str | None:
    """The start time the pre-execution hook left, consuming it. None if stale.

    Consumed on read so one start time can never be attributed to two runs.
    """
    global _pending_start
    pending, _pending_start = _pending_start, None
    if pending is None:
        return None
    try:
        age = (
            dt.datetime.now(dt.timezone.utc) - dt.datetime.fromisoformat(pending)
        ).total_seconds()
    except (TypeError, ValueError):
        return None
    if age < 0 or age > MAX_PENDING_START_AGE_S:
        log(f"discarding an orphaned start time ({age:.0f}s old) rather than "
            f"reporting it as a duration (§8.4)", WARNING)
        return None
    return pending


def handle_post_execution(scope: dict) -> None:
    """Called by the generated hook script with its whole namespace.

    Takes the namespace rather than named arguments precisely because what
    QGIS provides is the open empirical question (§5.11). Whatever is there
    gets used; whatever is missing degrades rather than raising.
    """
    global _namespace_logged

    try:
        if not _namespace_logged:
            names = sorted(k for k in scope if not k.startswith("_"))
            log(f"post-execution hook namespace: {names}. "
                f"Record this in docs/capture_coverage.md §4 (§5.11).", INFO)
            _namespace_logged = True

        engine = ProvenanceCaptureEngine.instance()
        if engine is None:
            return  # plugin not loaded; nothing to record, and that is fine

        algorithm = resolve_algorithm(scope.get("alg") or scope.get("algorithm"))
        facts = _algorithm_facts(algorithm)
        if not facts["algorithm_id"]:
            log("post-execution hook fired but the algorithm could not be "
                "identified — skipping (§5.11: record this case)", WARNING)
            return

        engine.record_algorithm_execution(
            algorithm_id=facts["algorithm_id"],
            algorithm_name=facts["algorithm_name"],
            provider=facts["provider"],
            parameters=scope.get("parameters"),
            parameter_definitions=parameter_definitions(algorithm),
            results=scope.get("results"),
            # A5 — the pre-execution hook left the start time in _pending_start.
            # If QGIS itself put one in the namespace, prefer that: it is the
            # more direct observation. Neither present means the engine defaults
            # to now and the run looks instantaneous, which is the pre-A5
            # limitation and stays recorded in docs/capture_coverage.md.
            started_at=scope.get("geoprovenance_started_at") or take_pending_start(),
            ended_at=scope.get("geoprovenance_ended_at") or utc_now_iso(),
            source="post_hook",
        )
    except Exception as exc:  # noqa: BLE001 — §5.1 [HARD]
        log_exception("post-execution hook", exc)


def _install_hook_script(hook_dir, *, when: str, filename: str, handler: str,
                         setting: str) -> Callable[[], None]:
    """Write one hook script and point a ProcessingConfig setting at it.

    Shared by the pre- and post-execution hooks, which differ only in those
    four values. Returns the undo (§5.3): it restores whatever the user had
    configured before, including an empty setting. Clobbering someone else's
    execution script is a defect, not a detail.
    """
    # Import first, write second. Writing the script before knowing whether
    # anything will ever run it left a generated file behind on a QGIS with no
    # Processing — a file nothing points at and unload has no undo for.
    try:
        from processing.core.ProcessingConfig import ProcessingConfig
    except ImportError as exc:
        log(f"Processing is not available, {when}-execution hook not installed: {exc}",
            WARNING)
        return lambda: None

    hook_dir = pathlib.Path(hook_dir)
    hook_dir.mkdir(parents=True, exist_ok=True)
    hook_path = hook_dir / filename

    plugin_parent = str(pathlib.Path(__file__).resolve().parents[2])
    hook_path.write_text(HOOK_TEMPLATE.format(
        plugin_parent=plugin_parent, handler=handler, when=when,
    ))

    # UNVERIFIED (§5.10) — the attribute name is an informed guess, so fall
    # back to the literal string rather than crashing on a rename.
    setting_name = getattr(ProcessingConfig, setting, setting)
    try:
        previous = ProcessingConfig.getSetting(setting_name)
    except Exception as exc:  # noqa: BLE001 — §5.1
        log_exception(f"could not read the existing {setting} setting", exc)
        return lambda: None

    try:
        ProcessingConfig.setSettingValue(setting_name, str(hook_path))
    except Exception as exc:  # noqa: BLE001
        log_exception(f"could not install the {when}-execution hook", exc)
        return lambda: None

    if previous:
        log(f"{when}-execution hook installed; your previous script ({previous}) "
            f"will be restored when the plugin unloads (§5.3)", WARNING)
    else:
        log(f"{when}-execution hook installed at {hook_path}", INFO)

    def restore() -> None:
        try:
            ProcessingConfig.setSettingValue(setting_name, previous or "")
            log(f"{when}-execution hook removed, previous setting restored", INFO)
        except Exception as exc:  # noqa: BLE001
            log_exception(f"could not restore {setting}", exc)

    return restore


def install_post_execution_hook(hook_dir) -> Callable[[], None]:
    """Point ProcessingConfig's post-execution setting at our script (§5.3)."""
    return _install_hook_script(
        hook_dir, when="post", filename=HOOK_FILENAME,
        handler="handle_post_execution", setting="POST_EXECUTION_SCRIPT",
    )


def install_pre_execution_hook(hook_dir) -> Callable[[], None]:
    """Point ProcessingConfig's pre-execution setting at our script (A5).

    This exists only to stamp a start time. Without it the post hook is the
    sole observer and it fires after the run, so every job looked
    instantaneous and `post_hook` durations were unreportable in RQ2 (§8.4).
    """
    return _install_hook_script(
        hook_dir, when="pre", filename=PRE_HOOK_FILENAME,
        handler="handle_pre_execution", setting="PRE_EXECUTION_SCRIPT",
    )


