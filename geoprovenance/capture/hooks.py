# channel 2: the processing.run wrapper
# ---------------------------------------------------------------------------

def install_run_wrapper(engine: ProvenanceCaptureEngine) -> Callable[[], None]:
    """Monkeypatch processing.run. Returns the un-patch (§5.4).

    The fallback channel for when the hook does not fire — and, until we know
    empirically where it does, a second observation of every scripted run. The
    duplicate is not waste: the two channels are de-duplicated on arrival
    (§5.9) and the difference between them is the RQ1 result (§8.3).
    """
    try:
        import processing
        from processing.tools import general
    except ImportError as exc:
        log(f"Processing is not available, run wrapper not installed: {exc}", WARNING)
        return lambda: None

    original = general.run
    if getattr(original, "_geoprovenance_wrapped", False):
        log("processing.run is already wrapped — not wrapping twice", WARNING)
        return lambda: None

    @functools.wraps(original)
    def wrapper(algOrName, parameters=None, *args, **kwargs):  # noqa: N803 — QGIS name
        started_at = utc_now_iso()
        try:
            results = original(algOrName, parameters, *args, **kwargs)
        except BaseException:
            # §5.2 [HARD] — record the failure, then re-raise UNTOUCHED. The
            # user's exception is theirs; we are only watching.
            _record(engine, algOrName, parameters, None, started_at, "failed")
            raise
        _record(engine, algOrName, parameters, results, started_at, "completed")
        return results

    wrapper._geoprovenance_wrapped = True  # noqa: SLF001 — our own marker

    general.run = wrapper
    processing.run = wrapper
    log("processing.run wrapper installed", INFO)

    def restore() -> None:
        general.run = original
        processing.run = original
        log("processing.run wrapper removed", INFO)

    return restore


def _record(engine, algorithm_or_id, parameters, results, started_at, status) -> None:
    """Observe one run from the wrapper. Never raises (§5.1)."""
    try:
        algorithm = resolve_algorithm(algorithm_or_id)
        facts = _algorithm_facts(algorithm)
        algorithm_id = facts["algorithm_id"] or (
            algorithm_or_id if isinstance(algorithm_or_id, str) else None
        )
        if not algorithm_id:
            return
        engine.record_algorithm_execution(
            algorithm_id=algorithm_id,
            algorithm_name=facts["algorithm_name"],
            provider=facts["provider"],
            parameters=parameters,
            parameter_definitions=parameter_definitions(algorithm),
            results=results,
            started_at=started_at,
            ended_at=utc_now_iso(),
            status=status,
            source="run_wrapper",
        )
    except Exception as exc:  # noqa: BLE001 — §5.1 [HARD]
        log_exception("processing.run wrapper", exc)


# ---------------------------------------------------------------------------

def install_all(engine: ProvenanceCaptureEngine, hook_dir) -> list[tuple[str, Callable]]:
    """Install both channels. Returns (description, undo) pairs for §5.4.

    Both are installed because until §5.11's coverage table is filled in we do
    not know which invocation paths the hook covers, and a missed execution is
    an RQ1 result we would rather measure than suffer.
    """
    return [
        ("restore the post-execution hook setting", install_post_execution_hook(hook_dir)),
        ("un-patch processing.run", install_run_wrapper(engine)),
    ]
